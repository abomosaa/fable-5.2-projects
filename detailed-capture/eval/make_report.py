#!/usr/bin/env python3
"""Generates docs/EVALUATION.md from eval/results/summary.json (numbers are copied from the measured results, never typed by hand)."""
import json, os, platform, subprocess

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
S = json.load(open(os.path.join(ROOT, "eval", "results", "summary.json")))
dev_path = os.path.join(ROOT, "eval", "results", "device_timing.json")
DEV = json.load(open(dev_path)) if os.path.exists(dev_path) else None


def f(v, n=2):
    return "–" if v is None else f"{v:.{n}f}"


def cpu():
    try:
        for line in open("/proc/cpuinfo"):
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except Exception:
        pass
    return platform.processor()


syn = [k for k in ("wave", "wave_distorted", "document", "repetitive", "relief") if k in S]
real = [k for k in S if k.startswith("real_")]
L = []
A = L.append
A("# Evaluation\n")
A("All numbers in this file are generated by `eval/make_report.py` from `eval/results/summary.json`, which is written by "
  "`eval/run_all.py` (synthetic) and `eval/run_real.py` (real photographs). Both drive the **same core commands the Android app "
  "calls** (`frame.add`, `register`, `coverage`, `compose`, `export.flat`) through the `dcap` CLI; scoring is done by "
  "`eval/evaluate.py`, an independent Python/OpenCV implementation that never sees the core's internals.\n")
A("Reproduce: `scripts/fetch_deps.sh && scripts/build_opencv_host.sh && cmake -S core -B build/core -G Ninja && cmake --build build/core && "
  "python eval/gen_synthetic.py datasets/synthetic/sets && python eval/run_all.py && python eval/run_real.py && python eval/make_report.py`\n")
A(f"Host used for the numbers below: {cpu()}, {os.cpu_count()} logical CPUs, Linux; the core ran with **{S.get('_environment', {}).get('threads_used', 4)} worker threads**.\n")

A("## 1. What is measured\n")
A("* **Synthetic sets** are rendered by `eval/gen_synthetic.py` from a known high-resolution source with a pinhole camera at random 3-D poses "
  "(position, pan/tilt ±5°, roll ±4°, distance ±5 %), optical blur + pixel-aperture integration (3× super-sampling), exposure ±12 %, white balance ±4 %, "
  "vignetting, sensor noise, 4:2:0 JPEG, and mixed EXIF orientations. The pipeline never sees poses. Overview and close-ups are 1600×1200 px.\n"
  "* **Registration error** compares every accepted frame's estimated transform with the true pose on a 9×7 grid, expressed in output pixels "
  "(absolute, relative to the true overview pose) and between overlapping frame pairs (relative — what causes seams and ghosting).\n"
  "* **Reconstruction quality** uses matched 768×768 windows: fused result vs. the pristine source re-sampled onto the output grid, and the same for "
  "the overview enlarged (bicubic) to identical dimensions. A per-channel gain/offset fit removes exposure differences for both. "
  "`f50` is the spatial frequency (cycles per output pixel) up to which the image stays coherent (magnitude-squared coherence ≥ 0.5) with the reference; "
  "sharpening or invented texture cannot raise it. `HF-corr` is the correlation of the detail band (image minus Gaussian σ=1.5).\n"
  "* **Real sets** have no ground truth. One close-up is withheld from the pipeline and used as an independent high-resolution reference for the area it "
  "covers (leave-one-out); it is located on the result by a separate OpenCV-Python SIFT+MAGSAC registration.\n")

A("## 2. Synthetic sets: acceptance and registration\n")
A("| set | photos | expected valid → accepted | expected invalid → not accepted | accepted but wrong (> 3 overview px) | abs. error mean / max (output px) | pairwise error mean / max (output px) | k1 true / estimated |")
A("|---|---|---|---|---|---|---|---|")
for k in syn:
    r = S[k]["registration"]
    A(f"| {k} | {S[k]['images']} | {r['expected_accept_accepted']} / {r['expected_accept']} | {r['expected_reject_not_accepted']} / {r['expected_reject']} | "
      f"{len(r['accepted_but_wrong_gt3ovpx'])} | {f(r['abs_err_out_px_mean'])} / {f(r['abs_err_out_px_max'])} | {f(r['pairwise_err_out_px_mean'])} / {f(r['pairwise_err_out_px_max'])} | "
      f"{r['k1_true']:.3f} / {r['k1_estimated_overview']:.4f} |")
A("")
A("Frames that were not accepted, with the reason shown to the user:\n")
A("| set | photo | ground-truth expectation | verdict | reasons |")
A("|---|---|---|---|---|")
for k in syn:
    for name, (exp, st, reasons) in sorted(S[k]["statuses"].items()):
        if st != "accepted":
            A(f"| {k} | {name} | {exp} | {st} | {', '.join(reasons)} |")
A("")
A("Notes: `repetitive` is a strictly periodic wallpaper with two unique landmarks; only the two close-ups containing a landmark can be placed uniquely. "
  "The others are reported as *uncertain: ambiguous_repeat* and are **not** composited (zero false placements). "
  "`relief` contains raised boxes photographed obliquely; its \"expected valid\" count is 0 because no planar result is correct there. "
  "The registration columns for `relief` only say that the frames are aligned to the BASE plane; raised content inside accepted frames is still "
  "in the wrong place unless it was masked — see \"Structural agreement with the overview\" below and docs/REVIEW.md. `document` close-ups 19/20 cover almost blank paper and line-pair targets.\n")

A("## 3. Synthetic sets: reconstruction vs. enlarged overview (windows fully covered by close-ups)\n")
A("| set | output | grid scale | est. genuine detail | windows | PSNR fused / overview (dB) | SSIM fused / overview | HF-corr fused / overview | f50 fused / overview (cyc/px) | resolution gain (f50) | residual shift median / max (px) |")
A("|---|---|---|---|---|---|---|---|---|---|---|")
for k in syn:
    q, res = S[k].get("quality_supported"), S[k].get("result")
    if not q or not res or not q.get("windows"):
        continue
    A(f"| {k} | {res['width']}×{res['height']} ({res['stats']['outputMP']:.1f} MP) | {res['scale']:.2f}× | {res['stats']['estimatedDetailMP']:.1f} MP "
      f"(overview {res['stats']['overviewMP']:.1f} MP) | {q['windows']} | {f(q['psnr_recon'])} / {f(q['psnr_base'])} | {f(q['ssim_recon'], 3)} / {f(q['ssim_base'], 3)} | "
      f"{f(q['hfncc_recon'], 3)} / {f(q['hfncc_base'], 3)} | {f(q['f50_recon'], 3)} / {f(q['f50_base'], 3)} | {f(q.get('resolution_gain_f50'))}× | {f(q['shift_med_px'])} / {f(q['shift_max_px'])} |")
A("")
A("Windows with **no** close-up coverage (the result must equal the enlarged overview there — nothing is invented):\n")
A("| set | windows | PSNR fused / overview (dB) | f50 fused / overview |")
A("|---|---|---|---|")
for k in syn:
    q = S[k].get("quality_overview_only")
    if q and q.get("windows"):
        A(f"| {k} | {q['windows']} | {f(q['psnr_recon'])} / {f(q['psnr_base'])} | {f(q['f50_recon'], 3)} / {f(q['f50_base'], 3)} |")
A("")

A("### Structural agreement with the overview (all sets)\n")
A("Reduced to the overview's resolution, a correct result must show the same content in the same place as the overview. The table gives the share of "
  "pixels whose low-pass difference to the overview exceeds 20 grey levels after a global tone fit — overall, and inside the area taken from close-ups. "
  "Misplaced content (false alignment, parallax that was not masked) raises it; it is the check that exposes what a planar model gets wrong on 3-D subjects.\n")
A("| set | area from close-ups | pixels differing from the overview (all) | … inside the close-up area | mean abs. difference (grey levels) |")
A("|---|---|---|---|---|")
for k in syn + real:
    c = S[k].get("overview_consistency")
    if c:
        A(f"| {k} | {c['closeup_area'] * 100:.0f} % | {c['frac_all'] * 100:.2f} % | {c['frac_in_closeup_area'] * 100:.2f} % | {c['mean_abs_diff']:.2f} |")
A("")

if "document" in S and S["document"].get("glyphs"):
    A("## 4. Readability of fine markings (document set)\n")
    A("Rows of random letters/digits at known positions; each glyph is classified by correlation against per-character templates taken from the pristine "
      "source (chance ≈ 3.5 %). No OCR language model is involved, so nothing can be \"guessed\" from context.\n")
    A("| cap height in the overview (px) | cap height in the source (px) | glyphs | correct in fused result | correct in enlarged overview |")
    A("|---|---|---|---|---|")
    for cap, g in sorted(S["document"]["glyphs"].items(), key=lambda kv: -int(kv[0])):
        A(f"| {g['cap_height_overview_px']} | {g['cap_height_source_px']} | {g['glyphs']} | {g['accuracy_fused'] * 100:.1f} % | {g['accuracy_overview_enlarged'] * 100:.1f} % |")
    A("")
    A("Line-pair targets (contrast of the fundamental relative to the pristine source; 1.0 = fully resolved):\n")
    A("| period in the overview (px) | period in the output (px) | fused | enlarged overview |")
    A("|---|---|---|---|")
    for b in S["document"]["bars"]:
        A(f"| {b['period_overview_px']} | {b['period_output_px']} | {f(b['contrast_fused_rel'])} | {f(b['contrast_overview_rel'])} |")
    A("")

A("## 5. Real photographs\n")
A("Sources and licences: `datasets/real/SOURCES.md`. These were taken by other people for other purposes (museum visits), hand-held, some obliquely, "
  "with compact cameras and DSLRs — they are not tuned inputs.\n")
A("| set | photos (MP of overview) | accepted | uncertain | rejected | output | grid scale | est. genuine detail | close-up area | register / fuse time (s) |")
A("|---|---|---|---|---|---|---|---|---|---|")
for k in real:
    e = S[k]
    st = [v[0] for v in e["statuses"].values()]
    res = e.get("result")
    A(f"| {k[5:]} | {e['images']} ({e['megapixels'].get('overview', e['megapixels'].get('overview.jpg', 0))} MP) | {st.count('accepted')} | {st.count('uncertain')} | {st.count('rejected')} | "
      + (f"{res['width']}×{res['height']} ({res['stats']['outputMP']:.0f} MP) | {res['scale']:.2f}× | {res['stats']['estimatedDetailMP']:.1f} MP | {res['stats']['closeupAreaFrac'] * 100:.0f} % | " if res else "– | – | – | – | ")
      + f"{e['timing'].get('register_s', 0):.1f} / {e['timing'].get('compose_s', 0):.1f} |")
A("")
A("Verdicts per photo (scale = close-up pixels per overview pixel):\n")
A("| set | photo | scale | verdict | reasons | warnings |")
A("|---|---|---|---|---|---|")
for k in real:
    for name, v in sorted(S[k]["statuses"].items()):
        A(f"| {k[5:]} | {name} | {f(v[3]) if v[3] else '–'} | {v[0]} | {', '.join(v[1])} | {', '.join(v[2])} |")
A("")
A("### Leave-one-out against a withheld close-up\n")
A("| set | withheld photo | frames used | windows | PSNR fused / overview (dB) | SSIM fused / overview | HF-corr fused / overview | f50 fused / overview | residual shift median / max (px) |")
A("|---|---|---|---|---|---|---|---|---|")
any_h = False
for k in real:
    for h in S[k].get("holdouts", []):
        any_h = True
        q = h.get("quality_supported")
        if not q or not h.get("windows_supported"):
            A(f"| {k[5:]} | {h['holdout']} | {h.get('frames_used', '–')} | 0 | {h.get('error', 'no window fully covered by other close-ups')} | | | | |")
            continue
        A(f"| {k[5:]} | {h['holdout']} | {h['frames_used']} | {h['windows_supported']} | {f(q['psnr_recon'])} / {f(q['psnr_base'])} | {f(q['ssim_recon'], 3)} / {f(q['ssim_base'], 3)} | "
          f"{f(q['hfncc_recon'], 3)} / {f(q['hfncc_base'], 3)} | {f(q['f50_recon'], 3)} / {f(q['f50_base'], 3)} | {f(q['shift_med_px'])} / {f(q['shift_max_px'])} |")
if not any_h:
    A("| – | no set had a close-up sufficiently covered by others | | | | | | | |")
A("")
A("The withheld photo is a different exposure (often a different viewpoint and lighting) than the frames used, so absolute PSNR/SSIM are bounded by "
  "real differences between photographs; the comparison between the two columns is what matters. Sets without a row had no close-up whose footprint "
  "is at least 45 % covered by another accepted close-up of similar scale.\n")

A("## 6. Deterministic tests\n")
A("`build/core/dcore_tests` (C++, no mocks, fixed seeds) — 9 tests:\n")
A("| test | covers |\n|---|---|\n"
  "| transform_composition | homography algebra, pixel-centre convention, radial model inverse, frame model round trip, validation of mirrored/folded/stretched transforms, edit transforms (4 quarter turns = identity, integral crops, inscribed rotation) |\n"
  "| exif_orientation | all 8 EXIF orientations (both byte orders): metadata, decoded pixels, continuous transform vs. raster permutation, exact 1/r reduced decoding |\n"
  "| registration_outliers | 45 % gross outliers, pure outliers, collinear (degenerate) and mirrored configurations, global refinement recovering perturbed transforms |\n"
  "| end_to_end_coverage_provenance | full pipeline on rendered views: registration error, coverage follows accepted footprints (exclude/undo), per-tile provenance sums to 1, source inspection, detail statistics, fused closer to truth than enlarged overview |\n"
  "| disconnected_graph_rejections_manual | island of mutually matching photos gets no position; blurred and same-scale photos rejected with reasons; manual correspondences |\n"
  "| tile_boundaries | 512 vs 1024 block layouts give identical pixels; pyramid levels are exact 2×2 averages across tile borders |\n"
  "| cancel_restart_resume | cancel mid-render keeps the previous result; journal; resume after dropping caches is bit-identical to an uninterrupted run; incremental block reuse; interrupted-job detection |\n"
  "| persistence_undo | undo/redo of edits and frame removal, byte-identical reload, originals untouched, damaged project file reported, invalid inputs refused |\n"
  "| export_formats_edits | PNG/TIFF/BigTIFF lossless equality, streaming JPEG, exact rotation/crop, colour edit maths, scaled export, DZI package + viewer, JPEG size limit, odd sizes, ICC pass-through, measurement with/without reference |\n")
tests_log = os.path.join(ROOT, "eval", "results", "core_tests.txt")
if os.path.exists(tests_log):
    tail = [l for l in open(tests_log).read().splitlines() if l.strip()]
    A("Last run (`eval/results/core_tests.txt`): `" + tail[-1] + "`\n")

A("## 7. Performance\n")
A("Host (desktop CPU above, core limited to the stated worker threads):\n")
A("| set | photos | import + analysis (s) | registration (s) | fusion (s) | output |")
A("|---|---|---|---|---|---|")
for k in syn + real:
    e = S[k]
    res = e.get("result")
    A(f"| {k} | {e['images']} | {e['timing'].get('add_s', 0):.1f} | {e['timing'].get('register_s', 0):.1f} | {e['timing'].get('compose_s', 0):.1f} | "
      + (f"{res['width']}×{res['height']}" if res else "–") + " |")
A("")
if DEV:
    A("On the Android emulator (" + DEV.get("device", "") + "):\n")
    A("| step | measured |")
    A("|---|---|")
    for row in DEV.get("rows", []):
        A(f"| {row[0]} | {row[1]} |")
    A("")
    A(DEV.get("note", "") + "\n")
A("## 8. Limits of this evaluation\n")
A("* Synthetic frames are rendered, not photographed; they model geometry, sampling, blur, noise, exposure and JPEG, but not rolling shutter, "
  "chromatic aberration, focus breathing or real specular reflections.\n"
  "* Real sets come from four subjects and a handful of cameras. No physical phone was available, so no set was captured with the app's own camera screen "
  "(see docs/DEVICE_VERIFICATION.md).\n"
  "* `f50` and the glyph classifier measure agreement with a reference; they say nothing about colour fidelity.\n"
  "* The estimated genuine detail is an estimate (sampling × relative sharpness), not a measurement.\n")
open(os.path.join(ROOT, "docs", "EVALUATION.md"), "w").write("\n".join(L) + "\n")
print("wrote docs/EVALUATION.md", len(L), "lines")
